    static func apply(to rgb: SIMD3<Double>, strength: Double) -> SIMD3<Double> {
        var offset = SIMD3<Double>.zero
        for sample in samples {
            let distanceSquared = simd_distance_squared(rgb, sample.center)
            guard distanceSquared < radius * radius else { continue }
            let r = distanceSquared.squareRoot() / radius
            let t = 1 - r
            offset += sample.offset * (t * t * t * t * (1 + 4 * r))
        }
        let endpointFade = min(1, 50 * min(rgb.max(), 1 - rgb.min()))
        return simd_clamp(rgb + offset * (strength * endpointFade), .zero, SIMD3(repeating: 1))
    }
